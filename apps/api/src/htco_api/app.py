class Resource(Protocol):
    """Something the app opens at startup and closes at shutdown (a pool, an HTTP client)."""

    async def start(self) -> None: ...

    async def stop(self) -> None: ...


def _new_request_id() -> str:
    return str(uuid.uuid7())


def _operation_id(route: APIRoute) -> str:
    """Operation IDs are the route function names (`healthz`), stable for generated clients."""
    return route.name


def _document_response(status: str, response: dict[str, Any]) -> None:
    """Add the request-ID header; error bodies are documented as `application/problem+json`.

    FastAPI files an error response's model under the route's media type (`application/json`)
    even when the response declares `application/problem+json`, so the schema is moved there.
    """
    response.setdefault("headers", {})["X-Request-Id"] = {
        "description": "ID of this request, generated by the server. Quote it when reporting a "
        "problem.",
        "required": True,
        "schema": {"type": "string", "format": "uuid"},
    }
    content = response.get("content", {})
    if status[0] in "45" and PROBLEM_MEDIA_TYPE in content and "application/json" in content:
        content[PROBLEM_MEDIA_TYPE] = content.pop("application/json")


class HtcoAPI(FastAPI):
    """FastAPI whose OpenAPI document matches what the middleware and handlers really send."""

    @override
    def openapi(self) -> dict[str, Any]:
        if self.openapi_schema is None:
            schema = super().openapi()
            for path_item in schema.get("paths", {}).values():
                for operation in path_item.values():
                    for status, response in operation.get("responses", {}).items():
                        _document_response(status, response)
        return super().openapi()


@dataclass(frozen=True)
class AppOptions:
    """What the composition root injects; the defaults suit tests and local runs."""

    readiness_checks: Sequence[ReadinessCheck] = ()
    readiness_timeout_seconds: float = 2.0
    new_request_id: Callable[[], str] = _new_request_id
    diagnostics: bool = False
    error_reporter: ErrorReporter = field(default_factory=NoErrorReporter)
    tracer_provider: TracerProvider | None = None
    # Verifies bearer tokens for `CurrentAuth`; without it, authenticated routes answer 503.
    authenticator: Authenticator | None = None
    # Started in order with the app, stopped in reverse order.
    resources: Sequence[Resource] = ()
    # Reads the caller's shops for `/v1/shops`; without it, that route answers 503.
    shops: ShopReader | None = None
    # Member and shop-access changes; without it, those routes answer 503.
    access: AccessStore | None = None
    # Creates invitation links; without it, `POST …/invitations` answers 503.
    inviter: Inviter | None = None
    # Cookie sign-in for the web app (BFF); without it, `/v1/auth/*` answers 503.
    web_auth: WebAuth | None = None
    # The Etsy connect flow (slice 4.3); without it, the connect endpoints answer 503.
    etsy: EtsyConnect | None = None
    # Connection health for the shop card (slice 4.4); without it, that route answers 503.
    integrations: IntegrationReader | None = None
    # Capability probes (slice 4.5); without them, re-checking answers 503.
    capability_checks: CapabilityChecks | None = None
    # Disconnect (slice 4.7) deletes tokens through the vault; without it, disconnect answers 503.
    token_vault: DisconnectingVault | None = None
    # Removes a shop with all its stored data; without it, removing answers 503.
    shop_remover: ShopRemover | None = None
    # The connected shop's live data (overview, orders, listings, reviews, shipping); without
    # it, those routes answer 503.
    dashboard: ShopDashboard | None = None
    clock: Callable[[], datetime] = lambda: datetime.now(UTC)


def _lifespan(resources: Sequence[Resource]) -> Callable[[FastAPI], Any]:
    @asynccontextmanager
    async def lifespan(_: FastAPI) -> AsyncIterator[None]:
        started: list[Resource] = []
        try:
            for resource in resources:
                await resource.start()
                started.append(resource)
            yield
        finally:
            for resource in reversed(started):
                await resource.stop()

    return lifespan


def create_app(options: AppOptions | None = None) -> FastAPI:
    """Build the API. Interactive docs and `/openapi.json` are off: the contract is the
    committed `packages/contracts/openapi.yaml` (ASVS 13.4.5)."""
    options = options or AppOptions()
    app = HtcoAPI(
        title="HTCO API",
        summary="Backend API of HTCO OS.",
        version="0.1.0",
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
        generate_unique_id_function=_operation_id,
        lifespan=_lifespan(options.resources),
    )
    app.state.authenticator = options.authenticator
    app.state.shops = options.shops
    app.state.access = options.access
    app.state.inviter = options.inviter
    app.state.web_auth = options.web_auth
    app.state.etsy = options.etsy
    app.state.integrations = options.integrations
    app.state.capability_checks = options.capability_checks
    app.state.token_vault = options.token_vault
    app.state.shop_remover = options.shop_remover
    app.state.dashboard = options.dashboard
    app.state.clock = options.clock
    app.include_router(
        health_router(
            readiness_checks=options.readiness_checks,
            timeout_seconds=options.readiness_timeout_seconds,
        ),
        responses=UNEXPECTED_ERROR_RESPONSES,
    )
    app.include_router(identity_router(clock=options.clock), responses=UNEXPECTED_ERROR_RESPONSES)
    app.include_router(access_router(clock=options.clock), responses=UNEXPECTED_ERROR_RESPONSES)
    app.include_router(web_auth_router(clock=options.clock), responses=UNEXPECTED_ERROR_RESPONSES)
    app.include_router(etsy_router(clock=options.clock), responses=UNEXPECTED_ERROR_RESPONSES)
    app.include_router(shop_data_router(clock=options.clock), responses=UNEXPECTED_ERROR_RESPONSES)
    if options.diagnostics:
        app.include_router(diagnostics_router(), responses=UNEXPECTED_ERROR_RESPONSES)
    add_problem_handlers(app)
    tracer_provider = options.tracer_provider or TracerProvider()
    # The last middleware added runs first: security headers wrap everything, including the
    # 500 response the request-context middleware produces.
    app.add_middleware(
        RequestContextMiddleware,
        new_request_id=options.new_request_id,
        tracer=tracer_provider.get_tracer("htco_api"),
        error_reporter=options.error_reporter,
    )
    app.add_middleware(SecurityHeadersMiddleware)
    return app

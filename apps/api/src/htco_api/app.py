"""The FastAPI application factory."""

import uuid
from collections.abc import Callable, Sequence
from typing import Any, override

from fastapi import FastAPI
from fastapi.routing import APIRoute

from htco_api.health import health_router
from htco_api.middleware import RequestContextMiddleware, SecurityHeadersMiddleware
from htco_api.problems import PROBLEM_MEDIA_TYPE, add_problem_handlers
from htco_platform.readiness import ReadinessCheck


def _new_request_id() -> str:
    return str(uuid.uuid7())


def _operation_id(route: APIRoute) -> str:
    """Operation IDs are the route function names (`healthz`), stable for generated clients."""
    return route.name


def _document_response(status: str, response: dict[str, Any]) -> None:
    """Add the request-ID header; error bodies are documented as `application/problem+json`.

    FastAPI files an error response's model under the route's media type (`application/json`)
    even when the response declares `application/problem+json`, so the schema is moved there.
    """
    response.setdefault("headers", {})["X-Request-Id"] = {
        "description": "ID of this request, generated by the server. Quote it when reporting a "
        "problem.",
        "required": True,
        "schema": {"type": "string", "format": "uuid"},
    }
    content = response.get("content", {})
    if status[0] in "45" and PROBLEM_MEDIA_TYPE in content and "application/json" in content:
        content[PROBLEM_MEDIA_TYPE] = content.pop("application/json")


class HtcoAPI(FastAPI):
    """FastAPI whose OpenAPI document matches what the middleware and handlers really send."""

    @override
    def openapi(self) -> dict[str, Any]:
        if self.openapi_schema is None:
            schema = super().openapi()
            for path_item in schema.get("paths", {}).values():
                for operation in path_item.values():
                    for status, response in operation.get("responses", {}).items():
                        _document_response(status, response)
        return super().openapi()


def create_app(
    *,
    readiness_checks: Sequence[ReadinessCheck] = (),
    readiness_timeout_seconds: float = 2.0,
    new_request_id: Callable[[], str] = _new_request_id,
) -> FastAPI:
    """Build the API. Interactive docs and `/openapi.json` are off: the contract is the
    committed `packages/contracts/openapi.yaml` (ASVS 13.4.5)."""
    app = HtcoAPI(
        title="HTCO API",
        summary="Backend API of HTCO OS.",
        version="0.1.0",
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
        generate_unique_id_function=_operation_id,
    )
    app.include_router(
        health_router(readiness_checks=readiness_checks, timeout_seconds=readiness_timeout_seconds)
    )
    add_problem_handlers(app)
    # The last middleware added runs first: security headers wrap everything, including the
    # 500 response the request-context middleware produces.
    app.add_middleware(RequestContextMiddleware, new_request_id=new_request_id)
    app.add_middleware(SecurityHeadersMiddleware)
    return app
